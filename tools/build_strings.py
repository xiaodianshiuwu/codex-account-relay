#!/usr/bin/env python3
"""Generate the four Localizable.strings files from i18n/strings.json.

The JSON file is the single source of truth for user-visible UI strings.
`--check` validates that every language is complete, placeholders match the
source key, and the checked-in .strings files are byte-for-byte current.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = [ROOT / "i18n" / "strings.json", ROOT / "i18n" / "cli.json"]
LANGUAGES = ("zh-Hans", "zh-Hant", "en", "ja")
PLACEHOLDER = re.compile(r"%(?:\d+\$)?(?:@|lld|ld|d|i|s|\.\d+f|f)")

TARGETS = {
    "desktop": ROOT / "desktop" / "Resources",
    "package": ROOT / "codex_relay" / "resources",
}


def placeholders(value: str) -> list[str]:
    return sorted(PLACEHOLDER.findall(value))


def quoted(value: str) -> str:
    # JSON string escaping is compatible with the .strings grammar for the
    # characters used by this project (quotes, backslashes and newlines).
    return json.dumps(value, ensure_ascii=False)


def render(language: str, table: dict[str, dict[str, str]]) -> str:
    lines = [
        f"/* Codex Relay UI strings — {language}.",
        "   Generated from i18n/strings.json; do not edit this file manually. */",
        "",
    ]
    for key in sorted(table):
        lines.append(f"{quoted(key)} = {quoted(table[key][language])};")
    lines.append("")
    return "\n".join(lines)


def validate(table: dict[str, dict[str, str]]) -> list[str]:
    errors: list[str] = []
    if not table:
        return ["i18n/strings.json is empty"]
    for key, entry in sorted(table.items()):
        if not key.strip():
            errors.append("empty translation key")
        reference = placeholders(key)
        for language in LANGUAGES:
            value = entry.get(language)
            if not isinstance(value, str) or not value.strip():
                errors.append(f"missing {language} translation: {key!r}")
                continue
            if placeholders(value) != reference:
                errors.append(
                    f"placeholder mismatch in {language} for {key!r}: "
                    f"expected {reference}, got {placeholders(value)}"
                )
    return errors


def load_sources() -> dict[str, dict[str, str]]:
    merged: dict[str, dict[str, str]] = {}
    for source in SOURCES:
        if not source.exists():
            continue
        try:
            table = json.loads(source.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            raise RuntimeError(f"cannot read {source}: {exc}") from exc
        if not isinstance(table, dict):
            raise RuntimeError(f"{source} must be a JSON object")
        for key, entry in table.items():
            if key in merged and merged[key] != entry:
                raise RuntimeError(f"conflicting translation for {key!r} in {source}")
            merged[key] = entry
    return merged


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files without writing")
    args = parser.parse_args(argv)

    try:
        table = load_sources()
    except RuntimeError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if not isinstance(table, dict):
        print("error: i18n catalogs must be JSON objects", file=sys.stderr)
        return 1

    errors = validate(table)
    if errors:
        for error in errors:
            print(f"error: {error}", file=sys.stderr)
        return 1

    stale: list[pathlib.Path] = []
    for language in LANGUAGES:
        text = render(language, table)
        for target_root in TARGETS.values():
            target = target_root / f"{language}.lproj" / "Localizable.strings"
            if args.check:
                if not target.exists() or target.read_text(encoding="utf-8") != text:
                    stale.append(target)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
    if args.check:
        for target in stale:
            print(f"error: generated strings are stale: {target}", file=sys.stderr)
        if stale:
            return 1
        print(f"i18n OK: {len(table)} keys × {len(LANGUAGES)} languages")
        return 0
    print(f"wrote {len(table)} keys × {len(LANGUAGES)} languages to {len(TARGETS)} resource trees")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
